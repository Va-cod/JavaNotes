package fundamentals;
import java.lang.String;
import java.util.Arrays;

public class Variables {
    public static void main(String[] args) {
        System.out.println("* * * * * * VARIABLES * * * * * *");

        String name = "Sergio Perez";
        String country = "Mexico";            // string -> stores text strings consisting of multiple characters.
        int age = 35;                         // int -> stores whole numbers up to 2 billion.
        char gender = 'M';                    // char -> stores a single text character.
        String racingTeam = "Cadillac";
        float stature = 1.78f;                // float -> stores fractional numbers with single precision.

        System.out.println("Name: " + name);
        System.out.println("Country: " + country);
        System.out.println("Racing Team: " + racingTeam);
        System.out.println("Age: " + age);
        System.out.println("Gender: " + gender);
        System.out.println("Stature: " + stature);





    }
}